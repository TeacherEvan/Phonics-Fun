#!/usr/bin/env node
/**
 * Generate the Java letter catalogue from the canonical JavaScript vocabulary.
 *
 * The two stacks had three independent copies of the letter/word data:
 *
 *   js/main.js                 apple, ant, airplane, alligator, arrow
 *   SymbolRenderer.java        apple, ant, airplane, alligator, arrow
 *   AudioManager.java          apple, ant
 *
 * so the native app taught a word ("bird" for letter B) that had no
 * recording, and the TTS fallback had no phrase for it either. The
 * JavaScript table is the canonical one; this script generates the Java
 * side from it, so the two cannot drift again.
 *
 * Usage:  node scripts/generate-java-catalog.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { PHONICS_FUN_LETTER_DATA } from '../js/letter-data.js';
import { VOICE_TEMPLATES } from '../js/letter-data.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const TARGET = path.join(
    ROOT,
    'app/src/main/java/com/phonicsfun/core/LetterCatalog.java',
);

/** Escape a string for inclusion in a Java string literal. */
function javaString(value) {
    return `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

const letters = Object.keys(PHONICS_FUN_LETTER_DATA);
const lines = [];

lines.push('package com.phonicsfun.core;');
lines.push('');
lines.push('import java.util.Collections;');
lines.push('import java.util.LinkedHashMap;');
lines.push('import java.util.List;');
lines.push('import java.util.Map;');
lines.push('');
lines.push('/**');
lines.push(' * LetterCatalogue - the A-Z picture vocabulary.');
lines.push(' *');
lines.push(
    ' * GENERATED by scripts/generate-java-catalog.mjs from the canonical',
);
lines.push(
    ' * JavaScript vocabulary in js/letter-data.js. Do not edit by hand: the',
);
lines.push(
    ' * two stacks had three independent copies of this table, which is how',
);
lines.push(' * the native app came to teach words that had no recording.');
lines.push(' */');
lines.push('public final class LetterCatalog {');
lines.push('');
lines.push('    private LetterCatalog() {');
lines.push('    }');
lines.push('');
lines.push('    /** Letter -> the five picture words for that letter. */');
lines.push(
    '    private static final Map<String, List<String>> WORDS = build();',
);
lines.push('');
lines.push('    /** The available voice packs, by public id. */');
lines.push(
    '    public static final List<String> VOICE_TEMPLATES = Collections.unmodifiableList(java.util.Arrays.asList(',
);
lines.push(
    '        ' +
        VOICE_TEMPLATES.map((t) => javaString(t.id)).join(', ') +
        '));',
);
lines.push('');
lines.push('    private static Map<String, List<String>> build() {');
lines.push('        Map<String, List<String>> map = new LinkedHashMap<>();');
for (const letter of letters) {
    const words = PHONICS_FUN_LETTER_DATA[letter];
    lines.push(
        `        map.put(${javaString(letter)}, Collections.unmodifiableList(java.util.Arrays.asList(${words
            .map(javaString)
            .join(', ')})));`,
    );
}
lines.push('        return Collections.unmodifiableMap(map);');
lines.push('    }');
lines.push('');
lines.push('    /**');
lines.push('     * The picture words for a letter.');
lines.push('     *');
lines.push('     * @param letter the letter, in any case');
lines.push('     * @return the words, or an empty list for an unknown letter');
lines.push('     */');
lines.push('    public static List<String> wordsForLetter(String letter) {');
lines.push('        if (letter == null) {');
lines.push('            return Collections.emptyList();');
lines.push('        }');
lines.push('        List<String> words = WORDS.get(letter.toUpperCase());');
lines.push(
    '        return words == null ? Collections.<String>emptyList() : words;',
);
lines.push('    }');
lines.push('');
lines.push('    /**');
lines.push('     * Every letter that has a vocabulary.');
lines.push('     *');
lines.push('     * @return the letters, in alphabetical order');
lines.push('     */');
lines.push('    public static List<String> letters() {');
lines.push(
    '        return Collections.unmodifiableList(new java.util.ArrayList<>(WORDS.keySet()));',
);
lines.push('    }');
lines.push('}');
lines.push('');

fs.writeFileSync(TARGET, lines.join('\n'), 'utf8');
console.log(
    `Generated ${TARGET.replace(ROOT + '/', '')} with ${letters.length} letters and ` +
        `${Object.values(PHONICS_FUN_LETTER_DATA).flat().length} words.`,
);
